# GET_FW Test
# ============================================================

import serial
import time

# ------------------------------------------------------------
# CONFIG
# ------------------------------------------------------------

PORT = "/dev/ttyACM0"
BAUDRATE = 115200

# ------------------------------------------------------------
# OPEN
# ------------------------------------------------------------

print("Opening serial...")

ser = serial.Serial(PORT, BAUDRATE, timeout=1)

time.sleep(2)

print("Connected")

# ------------------------------------------------------------
# SEND
# ------------------------------------------------------------

cmd = "GET_FW\n"

print("TX:", cmd.strip())

ser.write(cmd.encode())

# ------------------------------------------------------------
# RECEIVE
# ------------------------------------------------------------

timeout = time.time() + 5

while time.time() < timeout:

    if ser.in_waiting:

        line = ser.readline().decode(errors="ignore").strip()

        print("RX:", line)

# ------------------------------------------------------------
# CLOSE
# ------------------------------------------------------------

ser.close()

print("Done")

